#!/usr/bin/env python3
"""Generates the app's string catalog and L10n accessors from
apple/scripts/strings.json, which holds every string in English, German and
Croatian. Run it after changing that file."""
import json
import pathlib

root = pathlib.Path(__file__).resolve().parents[2]
strings = json.loads((root / "apple/scripts/strings.json").read_text())

catalog = {"sourceLanguage": "en", "version": "1.0", "strings": {}}
for key in sorted(strings):
    catalog["strings"][key] = {
        "extractionState": "manual",
        "localizations": {
            language: {"stringUnit": {"state": "translated", "value": value}}
            for language, value in strings[key].items()
        },
    }
(root / "apple/Pongo/Resources/Localizable.xcstrings").write_text(
    json.dumps(catalog, ensure_ascii=False, indent=2) + "\n")

lines = [
    "// Generated by apple/scripts/generate_strings.py; don't edit.",
    "",
    "import Foundation",
    "",
    "extension L10n {",
]
for key in sorted(strings):
    name = key if key[0].isalpha() else "_" + key
    lines.append(f"    static var `{name}`: String {{ tr(\"{key}\") }}")
lines += ["}", ""]
(root / "apple/Pongo/Shared/Strings.swift").write_text("\n".join(lines))
