#!/usr/bin/env python3
"""Generates the app's string catalog and L10n accessors from the Flutter
app's .arb files, plus apple/scripts/extra_strings.json for strings
only the Swift app has. Run it after changing either."""
import json
import pathlib

root = pathlib.Path(__file__).resolve().parents[2]
languages = ["en", "de", "hr"]
strings = {}
for language in languages:
    arb = json.loads((root / f"frontend/lib/l10n/app_{language}.arb").read_text())
    for key, value in arb.items():
        if not key.startswith("@"):
            strings.setdefault(key, {})[language] = value
extra = json.loads((root / "apple/scripts/extra_strings.json").read_text())
for key, values in extra.items():
    strings.setdefault(key, {}).update(values)

catalog = {"sourceLanguage": "en", "version": "1.0", "strings": {}}
for key in sorted(strings):
    catalog["strings"][key] = {
        "extractionState": "manual",
        "localizations": {
            language: {"stringUnit": {"state": "translated", "value": value}}
            for language, value in strings[key].items()
        },
    }
(root / "apple/Pongo/Resources/Localizable.xcstrings").write_text(
    json.dumps(catalog, ensure_ascii=False, indent=2) + "\n")

lines = [
    "// Generated by apple/scripts/generate_strings.py; don't edit.",
    "",
    "import Foundation",
    "",
    "extension L10n {",
]
for key in sorted(strings):
    name = key if key[0].isalpha() else "_" + key
    lines.append(f"    static var `{name}`: String {{ tr(\"{key}\") }}")
lines += ["}", ""]
(root / "apple/Pongo/Shared/Strings.swift").write_text("\n".join(lines))
